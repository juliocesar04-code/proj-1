function resolveLocale(value: string | null | undefined): Locale | null {
  if (!value) return null;
  const normalized = value.toLowerCase();

  if (normalized === "pt-br" || normalized.startsWith("pt")) return "pt-BR";
  if (normalized.startsWith("zh")) return "zh-CN";

  const direct = localeOptions.find(
    (option) => option.code.toLowerCase() === normalized,
  );
  if (direct) return direct.code;

  const base = normalized.split("-")[0];
  const baseMatch = localeOptions.find(
    (option) => option.code.toLowerCase().split("-")[0] === base,
  );
  return baseMatch?.code ?? null;
}

function initialLocale(): Locale {
  if (typeof window === "undefined") return "en";

  const saved = resolveLocale(window.localStorage.getItem("traceforge.locale"));
  if (saved) return saved;

  for (const language of navigator.languages ?? [navigator.language]) {
    const match = resolveLocale(language);
    if (match) return match;
  }

  return "en";
}

function interpolate(
  template: string,
  values?: Record<string, string | number>,
) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) =>
    String(values[key] ?? "{" + key + "}"),
  );
}

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  dir: "ltr" | "rtl";
  t: (key: string, values?: Record<string, string | number>) => string;
  formatNumber: (value: number, options?: Intl.NumberFormatOptions) => string;
  formatTime: (value: number) => string;
  evidenceText: (line: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(initialLocale);
  const dir = locale === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    window.localStorage.setItem("traceforge.locale", locale);
    document.documentElement.lang = locale;
    document.documentElement.dir = dir;
  }, [dir, locale]);

  const value = useMemo<I18nValue>(() => {
    const dictionary = dictionaries[locale];

    const t = (
      key: string,
      values?: Record<string, string | number>,
    ) => interpolate(dictionary[key] ?? en[key] ?? key, values);

    const formatNumber = (
      number: number,
      options?: Intl.NumberFormatOptions,
    ) => new Intl.NumberFormat(locale, options).format(number);

    const formatTime = (timestamp: number) =>
      new Intl.DateTimeFormat(locale, {
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit",
      }).format(timestamp);

    const evidenceText = (line: string) => {
      let match = line.match(
        /^(\d+)\/(\d+) spans ended in error \(([\d.]+)%\)\.$/,
      );
      if (match) {
        return t("evidence.error", {
          errors: match[1] ?? "",
          calls: match[2] ?? "",
          rate: formatNumber(Number(match[3] ?? 0), {
            maximumFractionDigits: 1,
          }),
        });
      }

      match = line.match(/^p95 latency reached ([\d.]+) ms\.$/);
      if (match) {
        return t("evidence.p95", {
          value: formatNumber(Number(match[1] ?? 0), {
            maximumFractionDigits: 1,
          }),
        });
      }

      match = line.match(
        /^([\d.]+) ms were spent inside the service after removing overlapping child calls\.$/,
      );
      if (match) {
        return t("evidence.self", {
          value: formatNumber(Number(match[1] ?? 0), {
            maximumFractionDigits: 1,
          }),
        });
      }

      if (line === "No strong error or latency signal was detected.") {
        return t("evidence.none");
      }

      return line;
    };

    return {
      locale,
      setLocale,
      dir,
      t,
      formatNumber,
      formatTime,
      evidenceText,
    };
  }, [dir, locale]);

  return (
    <I18nContext.Provider value={value}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
}
